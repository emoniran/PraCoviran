                    permite
                    distribuir el 10 % de la jornada anual de un trabajador de forma irregular, teniendo como
                    principal requisito el preaviso con 5 días de antelación.
                </p>
                <p class="mb-3">Esto ya se está aplicando en la mayoría de las plataformas, por lo que el SGH viene
                    a dar soporte informático para facilitar su gestión.
                </p>
                <p class="mb-3">El SGH nos permite controlar en qué días se realizan la distribución irregular, y el
                    saldo de la misma por trabajador.
