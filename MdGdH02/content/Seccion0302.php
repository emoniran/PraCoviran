        <p class="mb-3">
            Desde aquí se grabarán las horas extras. En la pantalla principal nos aparecerá la relación de todas
            las horas que llevamos grabadas, así como una serie de filtros para consultar cualquier información
            de una forma más concreta.
        </p>
        <p class="mb-3">
            Desde esta pantalla, también podemos editar cualquier registro grabado pulsando en el icono de
            “Gestionar”. Así mismo, si lo que queremos es eliminar el registro, pulsaremos en el icono de
            “Eliminar”.
        </p>
        <p class="mb-3">
            Estas posibilidades, Gestionar y Eliminar, tienen una limitación, ya que cuando una hora extra a
            pagar se haya abonado, es decir, se haya pagado en la nómina, quedará bloqueada y no aparecerán
            dichos iconos.
        </p>
        <p class="mb-3">
            Como norma general, sobre el día 20 de cada mes, se bloquearán todas las horas extras a pagar
            realizadas en el mes anterior, por lo que la revisión de las mismas debe ser anterior a esta fecha.
            Una vez bloqueadas, no se podrá modificar ni eliminar el registro de ninguna forma. Para crear un
            nuevo registro, es decir, para grabar la realización de una hora extra, debemos pulsar en “+ Crear
            Nuevo”.
        </p>
    </div>
    <div class="imagen"><img class="d-block mx-auto" src="imagenes/HER02.jpg" /></div>
    <div class="container">
        <p class="mb-3">
            Como podéis ver, al seleccionar el trabajador del cual vamos a grabar las horas extras, a la derecha
            nos aparece una información muy valiosa. Se trata de las horas extras pagadas que lleva grabadas
            durante el año, así como de las horas pendientes de compensar.
        </p>
        <p class="mb-3">
            <span class="text-decoration-underline text-center">Importante:</span> Si os fijáis, en el ejemplo que hemos
            puesto en la pantalla, al trabajador seleccionado se le han grabado 3 horas extras a compensar, y
            sin embargo aparece que debe compensar 5,25 horas. Esto se debe a que al tratarse de horas extras,
            el descanso debe guardar la misma proporción como si se fueran a pagar. Esto, en el caso del
            ejemplo, es de 1,75 horas por cada hora realizada. Este parámetro ya está configurado para cada
            plataforma, y permite ver de una forma clara el saldo horario a compensar de cada trabajador.
        </p>
        <p class="mb-3">
            Volviendo a la pantalla de grabación, una vez seleccionado el trabajador, debemos rellenar todos los
            campos y pulsar "Registrar". Sin salir de la pantalla de grabación, se pueden grabar varios
            registros de personas diferentes. La pantalla está optimizada para que la grabación se realice de la
            manera más rápida posible, y nos permite visualizar las grabaciones que estamos realizando.
        </p>
        <p class="mb-3">
            Hay que prestar especial atención al formato con que se graba la hora de inicio y la hora de fin. Se
            debe utilizar el formato hora, por lo que indicaremos 05:45, 06:50, 12:15, etc... En caso de que
            queramos grabar desde las 23:00 de un día a las 02:00 del día siguiente, debemos hacer dos registros
            diferentes, uno para cada día. Con la siguiente matización: el primer registro, se hará desde las
            23:00 a las 23:59. Esto se debe a que el sistema no admite el 24:00, ya que esta hora, en realidad,
            se corresponde con las 00:00 del día siguiente. El segundo registro sería desde las 00:00 hasta las
            02:00.
        </p>
        <p class="mb-3">
            También hay que tener en cuenta que
            <span class="fw-bold">el plazo máximo para grabar las horas extras a pagar es de 10 días desde su
                realización.</span>
            Es decir, el programa, de forma automática, no permitirá grabar horas extras con más de 10 días
            naturales de antigüedad.
        </p>
        <p class="mb-3">
            Todas las horas extras a pagar realizadas hasta el mes de abril de 2013 aparecerán grabadas en el
            nuevo sistema. Las horas extras realizadas desde mayo deberán grabarse en el SGH.
        </p>
