    <p>
        Al entrar al sistema, ésta es la pantalla que nos encontraremos. Como podéis observar, tiene tres áreas
        principales y otras dos accesorias:
    </p>

    <ul class="ms-3">
        <li class="mb-2">
            <strong>Horas Extras:</strong> Nos permite grabar la realización de horas extras, así como el
            disfrute de la compensación con descansos. <br>
        </li>
        <li class="mb-2">
            <strong>Horas Nocturnas/Festivas:</strong> Desde aquí se graba la realización de las horas nocturnas
            y festivas. <br>
        </li>
        <li class="mb-2">
            <strong>Distribución Irregular de la Jornada:</strong> Podremos gestionar cuándo un trabajador
            realiza horas de más o de menos, y nos mostrará el saldo horario que tiene. <br>
        </li>
        <br><br><br>
        <li class="mb-2">
            <strong>Gestión Incidencias:</strong> Se utiliza para informar a TIC's de cualquier problema técnico
            que exista.
        </li>
        <li class="mb-2">
            <strong>Listín Telefónico:</strong> Acceso rápido al listín oficial de teléfonos de la Organización.
        </li>
    </ul>
